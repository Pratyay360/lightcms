/**
 * Resolve a shortcode to an emoji. Exact names win; otherwise the first
 * shortcode with the query as a prefix is used (insertion order is stable).
 */
export function lookupEmoji(query: string): string | null {
  const name = query.toLowerCase();
  if (Object.hasOwn(EMOJI, name)) {
    return EMOJI[name];
  }
  for (const key of Object.keys(EMOJI)) {
    if (key.startsWith(name)) {
      return EMOJI[key];
    }
  }
  return null;
}
